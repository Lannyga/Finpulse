-- Materializar almacenamiento de las tablas existentes; no recrea objetos ni cambia filas.
-- Evita ORA-08177 en la primera escritura con transacciones SERIALIZABLE.
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET ECHO OFF VERIFY OFF DEFINE OFF SERVEROUTPUT ON LINESIZE 180
ALTER SESSION SET CONTAINER = FREEPDB1;
DECLARE n NUMBER;
BEGIN
    IF USER <> 'SYS' OR SYS_CONTEXT('USERENV','CON_NAME') <> 'FREEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20020,'Cuenta administrativa o contenedor incorrecto.');
    END IF;
    SELECT COUNT(*) INTO n FROM DBA_TABLES
    WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST')
    AND TABLE_NAME IN ('USUARIOS','CATEGORIAS','MOVIMIENTOS','PRESUPUESTOS','METAS_AHORRO','ESCENARIOS');
    IF n<>12 THEN RAISE_APPLICATION_ERROR(-20021,'Se requieren las seis tablas de ambos esquemas.'); END IF;
    FOR t IN (
        SELECT OWNER,TABLE_NAME FROM DBA_TABLES
        WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST')
        AND TABLE_NAME IN ('USUARIOS','CATEGORIAS','MOVIMIENTOS','PRESUPUESTOS','METAS_AHORRO','ESCENARIOS')
        AND SEGMENT_CREATED='NO'
    ) LOOP
        DBMS_SPACE_ADMIN.MATERIALIZE_DEFERRED_SEGMENTS(schema_name=>t.OWNER,table_name=>t.TABLE_NAME);
        DBMS_OUTPUT.PUT_LINE('Materializado '||t.OWNER||'.'||t.TABLE_NAME);
    END LOOP;
END;
/
SELECT OWNER,TABLE_NAME,SEGMENT_CREATED FROM DBA_TABLES
WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST') ORDER BY OWNER,TABLE_NAME;
EXIT
