-- Solo para un esquema VACIO FINPULSE_WEB o FINPULSE_WEB_TEST en FREEPDB1.
-- No ejecutar sobre la instalación existente. Oracle DDL confirma implícitamente.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF
DECLARE
    n NUMBER;
BEGIN
    IF USER NOT IN ('FINPULSE_WEB', 'FINPULSE_WEB_TEST') OR SYS_CONTEXT('USERENV', 'CON_NAME') <> 'FREEPDB1' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Esquema o contenedor incorrecto');
    END IF;
    SELECT COUNT(*) INTO n FROM USER_OBJECTS;
    IF n <> 0 THEN RAISE_APPLICATION_ERROR(-20002, 'El esquema debe estar vacío'); END IF;
END;
/

CREATE TABLE "USUARIOS" (
    "Id" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    "Username" NVARCHAR2(40) NOT NULL,
    "NormalizedName" NVARCHAR2(40) NOT NULL UNIQUE,
    "PasswordHash" NVARCHAR2(512) NOT NULL,
    -- Columnas de compatibilidad con la instalación anterior; sin funciones asociadas.
    "RecoveryHash" NVARCHAR2(512) DEFAULT 'disabled' NOT NULL,
    "WarningPercent" NUMBER(28,8) DEFAULT 80 NOT NULL,
    "SessionVersion" NVARCHAR2(32) NOT NULL,
    "Failures" NUMBER(10) NOT NULL,
    "Revision" NUMBER(19) NOT NULL,
    "LockedUntil" TIMESTAMP(7)
) SEGMENT CREATION IMMEDIATE;

CREATE TABLE "CATEGORIAS" (
    "Id" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    "Name" NVARCHAR2(80) NOT NULL,
    "Kind" NUMBER(10) NOT NULL CHECK ("Kind" IN (0,1)),
    UNIQUE ("Id", "Kind"),
    UNIQUE ("Kind", "Name")
) SEGMENT CREATION IMMEDIATE;

CREATE TABLE "METAS_AHORRO" (
    "Id" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    "Name" NVARCHAR2(120) NOT NULL,
    "Description" NVARCHAR2(500),
    "Target" NUMBER(19,2) NOT NULL CHECK ("Target" > 0 AND "Target" <= 1000000000),
    "Deadline" TIMESTAMP(7) NOT NULL,
    "UserId" NUMBER(19) NOT NULL REFERENCES "USUARIOS" ("Id"),
    "RequestKey" NVARCHAR2(32) NOT NULL,
    UNIQUE ("Id", "UserId"),
    UNIQUE ("UserId", "RequestKey")
) SEGMENT CREATION IMMEDIATE;

CREATE TABLE "MOVIMIENTOS" (
    "Id" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    "CategoryId" NUMBER(19),
    "GoalId" NUMBER(19),
    "Kind" NUMBER(10) NOT NULL,
    "Amount" NUMBER(19,2) NOT NULL CHECK ("Amount" > 0 AND "Amount" <= 1000000000),
    "Date" TIMESTAMP(7) NOT NULL,
    "Description" NVARCHAR2(500),
    "UserId" NUMBER(19) NOT NULL REFERENCES "USUARIOS" ("Id"),
    "RequestKey" NVARCHAR2(32) NOT NULL,
    CHECK (("Kind" IN (0,1) AND "CategoryId" IS NOT NULL AND "GoalId" IS NULL)
        OR ("Kind" = 2 AND "CategoryId" IS NULL AND "GoalId" IS NOT NULL)),
    FOREIGN KEY ("CategoryId", "Kind") REFERENCES "CATEGORIAS" ("Id", "Kind"),
    FOREIGN KEY ("GoalId", "UserId") REFERENCES "METAS_AHORRO" ("Id", "UserId"),
    UNIQUE ("UserId", "RequestKey")
) SEGMENT CREATION IMMEDIATE;

CREATE INDEX "IX_MOVIMIENTOS_UserId_Date" ON "MOVIMIENTOS" ("UserId", "Date");
CREATE INDEX "IX_MOVIMIENTOS_GoalId_UserId" ON "MOVIMIENTOS" ("GoalId", "UserId");
CREATE INDEX "IX_MOVIMIENTOS_CategoryId_Kind" ON "MOVIMIENTOS" ("CategoryId", "Kind");
