-- Solo lectura; ejecutar con cuenta administrativa autorizada. No lee hashes ni credenciales.
SET ECHO OFF VERIFY OFF DEFINE OFF PAGESIZE 200 LINESIZE 220 LONG 12000 LONGCHUNKSIZE 12000
WHENEVER SQLERROR EXIT SQL.SQLCODE
SELECT USER AS USUARIO, SYS_CONTEXT('USERENV','CON_NAME') AS CONTENEDOR,
       SYS_CONTEXT('USERENV','ISDBA') AS ES_ADMIN FROM DUAL;
SELECT CON_ID, USERNAME, ACCOUNT_STATUS FROM CDB_USERS
WHERE USERNAME IN ('FINPULSE_WEB','FINPULSE_WEB_TEST') ORDER BY CON_ID, USERNAME;
ALTER SESSION SET CONTAINER = FREEPDB1;
SELECT USER AS USUARIO, SYS_CONTEXT('USERENV','CON_NAME') AS CONTENEDOR FROM DUAL;
SELECT USERNAME, ACCOUNT_STATUS, DEFAULT_TABLESPACE FROM DBA_USERS
WHERE USERNAME IN ('FINPULSE_WEB','FINPULSE_WEB_TEST');
SELECT GRANTEE, PRIVILEGE, ADMIN_OPTION FROM DBA_SYS_PRIVS
WHERE GRANTEE IN ('FINPULSE_WEB','FINPULSE_WEB_TEST','SYS')
AND (GRANTEE <> 'SYS' OR PRIVILEGE IN ('CREATE USER','CREATE TABLE','CREATE SEQUENCE','GRANT ANY PRIVILEGE'))
ORDER BY GRANTEE, PRIVILEGE;
SELECT GRANTEE, GRANTED_ROLE, DEFAULT_ROLE FROM DBA_ROLE_PRIVS
WHERE GRANTEE IN ('FINPULSE_WEB','FINPULSE_WEB_TEST');
SELECT USERNAME, TABLESPACE_NAME, BYTES, MAX_BYTES FROM DBA_TS_QUOTAS
WHERE USERNAME IN ('FINPULSE_WEB','FINPULSE_WEB_TEST');
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS FROM DBA_OBJECTS
WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST') ORDER BY OWNER, OBJECT_TYPE, OBJECT_NAME;
SELECT OWNER, TABLE_NAME FROM DBA_TABLES
WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST') ORDER BY OWNER, TABLE_NAME;
SELECT OWNER, INDEX_NAME, TABLE_NAME, UNIQUENESS, STATUS FROM DBA_INDEXES
WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST') ORDER BY OWNER, TABLE_NAME, INDEX_NAME;
SELECT OWNER, CONSTRAINT_NAME, TABLE_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED,
       R_OWNER, R_CONSTRAINT_NAME FROM DBA_CONSTRAINTS
WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST') ORDER BY OWNER, TABLE_NAME, CONSTRAINT_NAME;
SELECT OWNER, TABLE_NAME, COLUMN_NAME, GENERATION_TYPE, SEQUENCE_NAME FROM DBA_TAB_IDENTITY_COLS
WHERE OWNER IN ('FINPULSE_WEB','FINPULSE_WEB_TEST');
-- Lista permitida: unicamente CREATE TABLE, nunca CREATE USER/CONNECT ni texto arbitrario.
SELECT SQL_ID, PARSING_SCHEMA_NAME, SQL_FULLTEXT FROM V$SQL
WHERE PARSING_SCHEMA_NAME IN ('FINPULSE_WEB','FINPULSE_WEB_TEST')
AND REGEXP_LIKE(SQL_TEXT, '^CREATE TABLE', 'i');
SELECT EVENT_TIMESTAMP, DBUSERNAME, ACTION_NAME, OBJECT_SCHEMA, OBJECT_NAME, RETURN_CODE, SQL_TEXT
FROM UNIFIED_AUDIT_TRAIL
WHERE DBUSERNAME IN ('FINPULSE_WEB','FINPULSE_WEB_TEST')
AND ACTION_NAME = 'CREATE TABLE' AND RETURN_CODE = 1031
ORDER BY EVENT_TIMESTAMP DESC FETCH FIRST 5 ROWS ONLY;
EXIT
