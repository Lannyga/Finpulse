CREATE TABLE FP_USUARIOS (
    USUARIO_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOMBRE_COMPLETO VARCHAR2(120 CHAR) NOT NULL,
    CORREO VARCHAR2(254 CHAR) NOT NULL,
    CLAVE_HASH VARCHAR2(300 CHAR) NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    INTENTOS_FALLIDOS NUMBER(3) DEFAULT 0 NOT NULL,
    BLOQUEADO_HASTA_UTC TIMESTAMP(6),
    FECHA_REGISTRO_UTC TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    ULTIMO_ACCESO_UTC TIMESTAMP(6),
    CONSTRAINT UQ_FP_USUARIOS_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_FP_USUARIOS_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT CK_FP_USUARIOS_INTENTOS CHECK (INTENTOS_FALLIDOS >= 0),
    CONSTRAINT CK_FP_USUARIOS_CORREO CHECK (CORREO = LOWER(CORREO))
);
COMMENT ON TABLE FP_USUARIOS IS 'Cuentas individuales de estudiantes para FINPULSE';
COMMENT ON COLUMN FP_USUARIOS.CLAVE_HASH IS 'PBKDF2-SHA256 con salt único, NO contraseña en texto plano';
